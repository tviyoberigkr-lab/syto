const bounded = (w) => new RegExp('(?<![\\p{L}\\p{N}])' + w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?![\\p{L}\\p{N}])', 'u');
const RE = new Map(STATIC_GLOSS.map((g) => [g.w, bounded(g.w)]));

/**
 * Доповнює пояснення від ШІ сталими. Нічого не замінює: якщо ШІ вже пояснив це саме слово (або слово, що
 * накладається), сталого не додаємо. Повертає новий масив [{w, e}] — або порожній, якщо пояснень немає.
 */
export function withStaticGloss(text, aiGloss) {
  const out = Array.isArray(aiGloss) ? aiGloss.filter((g) => g && typeof g.w === 'string' && typeof g.e === 'string') : [];
  const t = String(text ?? '');
  if (!t) return out;
  let added = 0;
  for (const g of STATIC_GLOSS) {
    if (added >= MAX_STATIC || out.length >= MAX_GLOSS_TOTAL) break;
    if (!RE.get(g.w).test(t)) continue;
    if (out.some((o) => o.w === g.w || o.w.includes(g.w) || g.w.includes(o.w))) continue;
    out.push({ ...g, s: 1 }); // s — пояснення зі словника, не від ШІ (інтерфейс не пише «Пояснення ШІ»)
    added++;
  }
  return out;
}
